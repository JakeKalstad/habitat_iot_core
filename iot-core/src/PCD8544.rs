use esp_idf_hal::gpio::{AnyIOPin, IOPin, OutputPin, PinDriver};
use esp_idf_hal::spi::{SpiDeviceDriver, SpiDriver};
use esp_idf_hal::{self, gpio, prelude::*, spi};
use esp_idf_sys::sleep;

pub struct PCD8544<'a> {
    pub spi: SpiDeviceDriver<'a, SpiDriver<'a>>, // Use SpiDeviceDriver
    pub dc_pin: PinDriver<'a, gpio::Gpio4, esp_idf_hal::gpio::InputOutput>, // Generic PinDriver for DC pin
    pub cs_pin: PinDriver<'a, gpio::Gpio15, esp_idf_hal::gpio::InputOutput>, // Generic PinDriver for DC pin
    pub reset_pin: PinDriver<'a, gpio::Gpio2, esp_idf_hal::gpio::InputOutput>, // Generic PinDriver for reset pin
    pub light_pin: PinDriver<'a, gpio::Gpio13, esp_idf_hal::gpio::InputOutput>, // Optional with generic PinDriver
}

impl<'a> PCD8544<'a> {
    pub fn init(&mut self) -> Result<(), anyhow::Error> {
        // Initialize the display (this depends on the PCD8544 datasheet)
        // Reset the display
        self.cs_pin.set_high().unwrap();
        self.reset_pin.set_low().unwrap();
        std::thread::sleep(std::time::Duration::from_millis(100)); // Small delay for reset
        self.reset_pin.set_high().unwrap();

        // Send initialization commands (PCD8544-specific)
        self.send_command(&[0x21, 0x13, 0xc2, 0x20, 0x9, 0x8, 0xc, 0x80, 0x40]).unwrap();
        self.send_command(&[0x0; 84 * 6]).unwrap();

        self.send_command(&[0xff; 84]).unwrap();

        Ok(())
    }

    pub fn write_char(&mut self, c: char) -> Result<(), anyhow::Error> {
        if let Some(index) = (c as u8).checked_sub(32) {
            if (index as usize) < FONT_6X8.len() {
                let glyph = &FONT_6X8[index as usize];
                self.send_data(glyph)?; // Send each byte of the glyph
                return Ok(());
            }
        }
        Err(anyhow::anyhow!("Character not supported: {}", c))
    }

    // Write a string to the display
    pub fn write_string(&mut self, s: &str) -> Result<(), anyhow::Error> {
        for c in s.chars() {
            self.write_char(c)?; // Write each character
        }
        Ok(())
    }

    fn send_command(&mut self, command: &[u8]) -> Result<(), anyhow::Error> {
        self.dc_pin.set_low().unwrap(); // DC low for command
        // self.cs_pin.set_low().unwrap();
        self.spi.write(command).unwrap(); // Use `write` to send the command byte
        // self.cs_pin.set_high().unwrap();
        Ok(())
    }

    pub fn send_data(&mut self, bytes: &[u8]) -> Result<(), anyhow::Error> {
        // dc high for data
        self.dc_pin.set_high().unwrap();
        // self.cs_pin.set_low().unwrap();
        
        self.spi.write(bytes).unwrap();
        // self.cs_pin.set_high().unwrap();
        Ok(())
    }
}

